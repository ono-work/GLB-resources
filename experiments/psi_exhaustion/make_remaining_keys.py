#!/usr/bin/env python3
"""Regenerate REMAINING_KEYS.json / .md from the key universe (audit_psi_exhaustiveness.universe) minus the keys owned by
v5 and by the ledger (COUNTED_FAMILIES.json).  Adds per key: P-cells (P = R ∩ G_2 spanned), mirror handling, status
(from the producer / verifier certificates on disk), HEURISTIC mass estimate (barrier/frontier_mass.json) and the
compressed producer / verifier plan (barrier/plan_runs_<id>.json).
Usage (from experiments/post_gpw_improvement): python3.11 ../psi_exhaustion/make_remaining_keys.py
"""
import sys, json, math
from pathlib import Path
OUTDIR = Path(__file__).resolve().parent
PG = OUTDIR.parent / "post_gpw_improvement"
sys.path.insert(0, str(OUTDIR)); sys.path.insert(0, str(PG)); sys.path.insert(0, str(PG / "harvest")); sys.path.insert(0, str(PG / "barrier"))
import verify_v2 as v
import audit_psi_exhaustiveness as ax
from plan_runs import FAM

PROD_S_PER_UNIT, VER_S_PER_UNIT = 2.5e-7, 5e-7      # calibrated on the measured N7 / N8 family runs


def fname(S, C): return f"psi_S{'_'.join(map(str, S)) or 'none'}_C{'_'.join(map(str, C)) or 'none'}"


def pcells(S, C):
    Z = 0 in C; F = [0, 3, 12, 21] if Z else [3, 12, 21]; T = list(S) if Z else [0] + list(S)
    E = [m for m in F if m not in S and m not in C]
    Vmax = [x for x in range(v.N) if x not in T and not any(v.comp(x, t) for t in T)]
    Y = [x for x in Vmax if x < 22 and x not in F and not any(v.leq(m, x) for m in C) and not any(v.leq(x, m) for m in E)]
    return [sorted(T + [y for i, y in enumerate(Y) if mk >> i & 1]) for mk in range(1 << len(Y))
            if v.antichain([y for i, y in enumerate(Y) if mk >> i & 1])]


def main():
    led = json.loads((PG / "COUNTED_FAMILIES.json").read_text())
    taken = {("0", (3, 12, 21), (), ()), ("0", (3, 12), (), (21,))}
    for e in led["families"]: taken.add((e["world"], tuple(sorted(e["S"])), tuple(sorted(e["C"])), tuple(sorted(e["E"]))))
    byk = {}
    for fid, (S, C) in FAM.items():
        Z = 0 in C; F = [0, 3, 12, 21] if Z else [3, 12, 21]
        byk[("Z" if Z else "0", tuple(sorted(S)), tuple(sorted(C)), tuple(m for m in F if m not in S and m not in C))] = fid
    mass = json.loads((PG / "barrier/frontier_mass.json").read_text())
    keys = []
    for k in ax.universe():
        if k in taken: continue
        fid = byk.get(k); assert fid, f"no plan id for {k}"
        S, C = list(k[1]), list(k[2])
        Sx = [x for x in FAM[fid][0]]; Cx = [x for x in FAM[fid][1]]
        prod = PG / "harvest" / (fname(Sx, Cx) + ".json"); ver = PG / "harvest/certificates" / ("verify_" + fname(Sx, Cx) + ".json")
        st = "not computed"
        if prod.exists(): st = "producer exact"
        if ver.exists() and json.loads(ver.read_text()).get("status") == "AUDIT PASSED": st = "independently verified"
        pl = json.loads((PG / f"barrier/plan_runs_{fid}.json").read_text())
        big = [r for r in pl["regions"] if "producer" in r]
        pw = sum(sum(r["producer"]["ranks_S"]) for r in big if not r["producer_cached"])
        vw = sum(r.get("verifier", {}).get("work", 0) for r in big if not r["verifier_cached"])
        mS = max((max(r["producer"]["ranks_S"]) for r in big), default=0)
        m = mass[fid]
        keys.append(dict(
            id=fid, key=ax.kid(k), world=k[0], S=S, C=C, E=list(k[3]), args=[Sx, Cx],
            P_cells=pcells(S, C), mirror="separate class (negation; -O0 / -OZ), counted as 2 x original",
            status=st, producer_certificate=str(prod.relative_to(PG)), verifier_certificate=str(ver.relative_to(PG)),
            est_log10_original=round(m["upper_log10"], 3), est_kind="HEURISTIC SIS leading term (factor ~3)",
            unique_regions=pl["unique_regions"], largest_region=max(r["n"] for r in pl["regions"]),
            regions_ge400_to_compute=sum(1 for r in big if not r["producer_cached"]),
            max_S=mS, w_eff=round(math.log(mS, 171), 3) if mS else None,
            producer_peak_GiB=round(max((8 * r["producer"]["stored"] / 2 ** 30 for r in big), default=0), 1),
            verifier_peak_GiB=max((r.get("verifier", {}).get("peak_GiB", 0) for r in big), default=0),
            producer_h=round(pw * PROD_S_PER_UNIT / 3600, 2), verifier_h=round(vw * VER_S_PER_UNIT / 3600, 2)))
    for r in keys:
        r["value_per_hour"] = 2 * 10 ** r["est_log10_original"] / max(r["producer_h"] + r["verifier_h"], 0.1)
    keys.sort(key=lambda r: -r["value_per_hour"])
    for i, r in enumerate(keys): r["rank"] = i + 1
    out = dict(note="Regenerated from the key universe (36 keys) minus v5 and COUNTED_FAMILIES.json; see audit_psi_exhaustiveness.py",
               n=len(keys), keys=keys)
    (OUTDIR / "REMAINING_KEYS.json").write_text(json.dumps(out, indent=1) + "\n")
    L = ["# Remaining Ψ keys", "",
         f"There are {len(keys)} keys. They are regenerated by `make_remaining_keys.py` as the universe of 36 keys minus the v5 keys and the ledger keys; `audit_psi_exhaustiveness.py` checks this.",
         "",
         "The estimates are HEURISTIC: the SIS leading term, accurate to a factor of about 3. They are used only for ranking.",
         "",
         "Times are projected from the measured N7 and N8 runs: producer 2.5e-7 s per compressed state per rank, verifier 5e-7 s per unit of sweep work.",
         "",
         "| rank | id | key | P-cells | status | est. log10 (orig.) | max S(B) | w_eff | prod. RAM | verif. RAM | prod. h | verif. h | value/h (×2) |",
         "|---:|---|---|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for r in keys:
        L.append(f"| {r['rank']} | {r['id']} | `{r['key']}` | {len(r['P_cells'])} | {r['status']} | {r['est_log10_original']} | {r['max_S']:.2e} | {r['w_eff']} | "
                 f"{r['producer_peak_GiB']} GiB | {r['verifier_peak_GiB']} GiB | {r['producer_h']} | {r['verifier_h']} | {r['value_per_hour']:.2e} |")
    L += ["", "The mirror of every key is the negated family. It lies in a separate class (`-O0` or `-OZ`) and is counted as 2 × the original.",
          "", "The exact P-cell lists (`P = R ∩ G_2`) are in `REMAINING_KEYS.json`."]
    (OUTDIR / "REMAINING_KEYS.md").write_text("\n".join(L) + "\n")
    for r in keys: print(r["rank"], r["id"], r["key"], r["status"], r["est_log10_original"], r["producer_h"], r["verifier_h"], f"{r['value_per_hour']:.2e}")


if __name__ == "__main__":
    main()
